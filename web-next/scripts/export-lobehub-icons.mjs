import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const library = new URL('../node_modules/@lobehub/icons/', import.meta.url)
const read = (path) => readFileSync(new URL(path, library), 'utf8')
const { version } = JSON.parse(read('package.json'))
const toc = JSON.parse(read('es/toc.json'))
const enumValues = new Map(
  [...read('es/features/providerEnum.js').matchAll(/ModelProvider\["([^"]+)"\] = "([^"]+)"/g)]
    .map(([, name, key]) => [name, key]),
)

function mappings(file, exportName) {
  const source = ts.createSourceFile(file, read(file), ts.ScriptTarget.ESNext, true, ts.ScriptKind.JS)
  const imports = new Map()
  let list
  for (const node of source.statements) {
    if (ts.isImportDeclaration(node) && node.importClause?.name && /^\.\.\/\w+$/.test(node.moduleSpecifier.text)) {
      imports.set(node.importClause.name.text, node.moduleSpecifier.text.slice(3))
    }
    if (!ts.isVariableStatement(node)) continue
    const target = node.declarationList.declarations.find(({ name }) => name.getText(source) === exportName)
    if (target) list = target.initializer
  }
  if (!list || !ts.isArrayLiteralExpression(list)) throw new Error(`Missing ${exportName}`)
  return list.elements.map((entry) => {
    if (!ts.isObjectLiteralExpression(entry)) throw new Error(`Invalid ${exportName} entry`)
    const properties = new Map(entry.properties.filter(ts.isPropertyAssignment)
      .map(({ name, initializer }) => [name.getText(source), initializer]))
    const icon = imports.get(properties.get('Icon')?.getText(source))
    const keywords = properties.get('keywords')
    if (!icon || !keywords || !ts.isArrayLiteralExpression(keywords)) throw new Error(`Unsupported icon mapping: ${entry.getText(source)}`)
    return [icon, keywords.elements.map((keyword) => {
      if (ts.isStringLiteral(keyword)) return keyword.text
      if (ts.isPropertyAccessExpression(keyword) && enumValues.has(keyword.name.text)) return enumValues.get(keyword.name.text)
      throw new Error(`Unsupported icon keyword: ${keyword.getText(source)}`)
    })]
  })
}

const providers = mappings('es/features/providerConfig.js', 'providerMappings')
const models = mappings('es/features/modelConfig.js', 'modelMappings')
const referenced = new Set([...providers, ...models].map(([icon]) => icon))
const entries = toc.filter(({ group, id }) => group === 'model' || group === 'provider' || referenced.has(id))
const registered = new Set(entries.map(({ id }) => id))
for (const id of referenced) if (!registered.has(id)) throw new Error(`Missing icon in package index: ${id}`)

const loaders = entries.map(({ id, title }) => {
  if (!/^\w+$/.test(id)) throw new Error(`Invalid icon module: ${id}`)
  const base = `es/${id}/components/`
  const variant = ['Color', 'Mono'].find((value) => existsSync(fileURLToPath(new URL(`${base}${value}.js`, library))))
  if (!variant) throw new Error(`Missing SVG component: ${id}`)
  return `  [${JSON.stringify(id)}, ${JSON.stringify(title)}, () => import('@lobehub/icons/${base}${variant}')],`
})
const array = (values) => values.map((value) => `  ${JSON.stringify(value)},`).join('\n')
const target = new URL('../src/components/brand/lobehub-icon-index.ts', import.meta.url)
const content = [
  `// Generated by scripts/export-lobehub-icons.mjs from @lobehub/icons ${version}.`,
  "import type { LogoComponent } from './model-logos'",
  '',
  'type IconLoader = () => Promise<{ default: LogoComponent }>',
  `export const lobeHubIconLoaders: readonly (readonly [string, string, IconLoader])[] = [\n${loaders.join('\n')}\n]`,
  `export const lobeHubProviderIconRules: readonly (readonly [string, readonly string[]])[] = [\n${array(providers)}\n]`,
  `export const lobeHubModelIconRules: readonly (readonly [string, readonly string[]])[] = [\n${array(models)}\n]\n`,
].join('\n')
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== content) throw new Error('LobeHub icon index is out of date')
} else {
  writeFileSync(target, content)
}
console.log(`${entries.length} SVG components, ${providers.length} provider mappings, ${models.length} model mappings`)

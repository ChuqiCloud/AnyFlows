use std::{error::Error, fs, io};

use af_domain::{ChannelType, CredentialKind, Protocol};
use serde_json::json;

use crate::workspace_root;

const OUTPUTS: [&str; 2] = [
    "web/src/features/channels/channel-capabilities.gen.ts",
    "web-next/src/features/channels/channel-capabilities.gen.ts",
];

pub(super) fn export() -> Result<(), Box<dyn Error>> {
    let expected = render()?;
    for output in OUTPUTS {
        fs::write(workspace_root().join(output), &expected)?;
    }
    println!("渠道能力目录已导出到两套前端");
    Ok(())
}

pub(super) fn check() -> Result<(), Box<dyn Error>> {
    let expected = render()?;
    for output in OUTPUTS {
        let committed = fs::read_to_string(workspace_root().join(output))?;
        if committed.replace("\r\n", "\n") != expected {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                format!("{output} 已过期，请运行 `cargo xtask channel-capabilities export`"),
            )
            .into());
        }
    }
    println!("渠道能力目录与 Rust 定义一致");
    Ok(())
}

fn render() -> Result<String, serde_json::Error> {
    let mut output = String::from(
        "// Generated by cargo xtask channel-capabilities export. Do not edit.\nexport const channelCapabilities = {\n",
    );
    let protocols = |channel: ChannelType, supports: fn(ChannelType, Protocol) -> bool| {
        Protocol::ALL
            .iter()
            .copied()
            .filter(|protocol| supports(channel, *protocol))
            .collect::<Vec<_>>()
    };
    let mut runtime_channels = Vec::new();
    for channel in ChannelType::ALL.iter().copied() {
        let runtime = protocols(channel, ChannelType::supports_runtime);
        if !runtime.is_empty() {
            runtime_channels.push(channel);
        }
        let credentials = CredentialKind::ALL
            .iter()
            .copied()
            .filter(|kind| channel.supports_credential_kind(*kind))
            .collect::<Vec<_>>();
        let capability = json!({
            "protocols": runtime,
            "probeProtocols": protocols(channel, ChannelType::supports_probe),
            "modelDiscoveryProtocols": protocols(channel, ChannelType::supports_model_discovery),
            "credentialKinds": credentials,
            "creatableCredentialKinds": channel.creatable_credential_kinds(),
        });
        output.push_str(&format!(
            "  {}: {},\n",
            channel.as_str(),
            serde_json::to_string(&capability)?,
        ));
    }
    output.push_str("} as const\n\nexport const runtimeChannelTypes = ");
    output.push_str(&serde_json::to_string(&runtime_channels)?);
    output.push_str(" as const\nexport const channelProtocols = ");
    output.push_str(&serde_json::to_string(Protocol::ALL)?);
    output.push_str(" as const\n");
    Ok(output)
}

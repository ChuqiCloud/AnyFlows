#!/usr/bin/env python3
"""Mirror public PR discussion into its private Gitea counterpart."""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from urllib.error import HTTPError, URLError
from urllib.request import HTTPRedirectHandler, Request, build_opener


MIRROR_MARKERS = (
    "<!-- anyflows-pr-sync-comment:",
    "<!-- gitea-source-comment:",
    "<!-- github-source-comment:",
)
EXPORT_BRANCH = "sync/gitea-public-core"


class SyncError(RuntimeError):
    pass


class NoRedirect(HTTPRedirectHandler):
    def redirect_request(self, request, response, code, message, headers, new_url):
        return None


class Api:
    def __init__(self, base, token, scheme):
        self.base = base.rstrip("/")
        self.headers = {
            "Authorization": f"{scheme} {token}",
            "Accept": "application/json",
            "User-Agent": "AnyFlows-PR-sync",
        }
        self.opener = build_opener(NoRedirect())

    def request(self, method, path, body=None):
        data = None if body is None else json.dumps(body, ensure_ascii=False).encode("utf-8")
        request = Request(
            self.base + path, data=data, method=method,
            headers={**self.headers, "Content-Type": "application/json"},
        )
        try:
            with self.opener.open(request, timeout=30) as response:
                content = response.read()
                return json.loads(content) if content else None
        except HTTPError as error:
            raise SyncError(f"{method} {path} returned HTTP {error.code}") from None
        except (URLError, TimeoutError, ValueError):
            raise SyncError(f"{method} {path} failed or returned invalid JSON") from None

    def pages(self, path, size_parameter, size):
        result = []
        page = 1
        separator = "&" if "?" in path else "?"
        while True:
            batch = self.request("GET", f"{path}{separator}{size_parameter}={size}&page={page}")
            if not isinstance(batch, list):
                raise SyncError(f"{path} did not return a list")
            result.extend(batch)
            if len(batch) < size:
                return result
            page += 1


def source_comment(comment):
    user = comment.get("user") or {}
    body = comment.get("body") or ""
    return (
        bool(body.strip())
        and user.get("type") != "Bot"
        and not (user.get("login") or "").endswith("[bot]")
        and not any(marker in body for marker in MIRROR_MARKERS)
    )


def source_id(comment, pr_number, sync_username):
    login = ((comment.get("user") or {}).get("login") or "").casefold()
    if not sync_username or login != sync_username.casefold():
        return None
    pattern = (
        rf"<!-- (?:anyflows-pr-sync-comment:github|github-source-comment):"
        rf"{pr_number}:([0-9]+) -->\s*\Z"
    )
    match = re.search(pattern, comment.get("body") or "")
    return int(match.group(1)) if match else None


def render_comment(comment, pr_number, pr_url):
    user = comment.get("user") or {}
    comment_id = comment["id"]
    marker = f"<!-- anyflows-pr-sync-comment:github:{pr_number}:{comment_id} -->"
    return (
        f"GitHub 用户 `{user.get('login', 'unknown')}`（{comment['created_at']}）\n\n"
        f"{comment['body']}\n\n{marker}"
    )


def find_target(gitea, repository, pr, public_repository):
    number = pr["number"]
    head = pr["head"]
    if (pr.get("base") or {}).get("ref") != "main":
        return None
    prefix = f"/repos/{repository}"
    if head["ref"] == EXPORT_BRANCH:
        if (head.get("repo") or {}).get("full_name") != public_repository:
            return None
        # This trailing marker is generated by the private export workflow.
        pattern = (
            rf"<!-- anyflows-pr-source:gitea:{re.escape(repository)}:"
            r"([0-9]+):([0-9a-f]{40}) -->\s*\Z"
        )
        match = re.search(pattern, pr.get("body") or "")
        if not match:
            return None
        target = gitea.request("GET", f"{prefix}/pulls/{int(match.group(1))}")
        if (
            not target.get("merged")
            or target.get("merge_commit_sha") != match.group(2)
            or (target.get("base") or {}).get("ref") != "develop"
        ):
            raise SyncError("The exported PR source does not match the private merge commit")
        return target["number"]
    if not pr.get("merged_at"):
        return None
    if not re.fullmatch(r"[0-9a-f]{40}", head["sha"]):
        raise SyncError("Invalid public PR head revision")
    branch = f"sync/github-pr-{number}-{head['sha']}"
    candidates = gitea.pages(f"{prefix}/pulls?state=all", "limit", 50)
    matches = [
        candidate for candidate in candidates
        if (candidate.get("head") or {}).get("ref") == branch
        and (candidate.get("base") or {}).get("ref") == "develop"
    ]
    if len(matches) > 1:
        raise SyncError("Multiple Gitea PRs match the public contribution")
    return matches[0]["number"] if matches else None


def mirror(github, gitea, public_repository, repository, sync_username, pr_number):
    pr = github.request("GET", f"/repos/{public_repository}/pulls/{pr_number}")
    target = find_target(gitea, repository, pr, public_repository)
    if target is None:
        print(f"No Gitea counterpart for GitHub PR #{pr_number}; nothing to mirror")
        return
    prefix = f"/repos/{repository}"
    account = gitea.request("GET", "/user")
    actual_username = account.get("login") or ""
    if not actual_username or actual_username.casefold() != sync_username.casefold():
        raise SyncError("Gitea sync username does not match the authenticated account")
    comments = github.pages(
        f"/repos/{public_repository}/issues/{pr_number}/comments", "per_page", 100
    )
    desired = {comment["id"]: comment for comment in comments if source_comment(comment)}
    existing = gitea.pages(f"{prefix}/issues/{target}/comments", "limit", 50)
    mirrored = {}
    for comment in existing:
        identity = source_id(comment, pr_number, sync_username)
        if identity is None:
            continue
        if identity not in desired or identity in mirrored:
            gitea.request("DELETE", f"{prefix}/issues/comments/{comment['id']}")
        else:
            mirrored[identity] = comment
    for identity, comment in desired.items():
        body = render_comment(comment, pr_number, pr["html_url"])
        previous = mirrored.get(identity)
        if previous is None:
            gitea.request("POST", f"{prefix}/issues/{target}/comments", {"body": body})
        elif previous.get("body") != body:
            gitea.request("PATCH", f"{prefix}/issues/comments/{previous['id']}", {"body": body})
    print(f"Mirrored GitHub PR #{pr_number} discussion to Gitea PR #{target}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pr", type=int, required=True)
    args = parser.parse_args()
    if args.pr < 1:
        parser.error("--pr must be positive")
    try:
        public_repository = os.environ["GITHUB_REPOSITORY"]
        repository = os.environ["GITEA_REPOSITORY"]
        sync_username = os.environ["GITEA_SYNC_USERNAME"]
        github = Api(os.environ["GITHUB_API_URL"], os.environ["GITHUB_TOKEN"], "Bearer")
        gitea = Api(os.environ["GITEA_BASE_URL"].rstrip("/") + "/api/v1", os.environ["GITEA_TOKEN"], "token")
        mirror(github, gitea, public_repository, repository, sync_username, args.pr)
    except (KeyError, SyncError) as error:
        print(f"Comment sync failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
